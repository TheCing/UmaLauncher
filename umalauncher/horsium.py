# Threads currently quitting replaced/hung drivers; joined at shutdown.
_PENDING_QUIT_THREADS = []

# When a browser can't start at all, every packet would otherwise trigger
# another launch attempt - each one flashing a window on screen and, every
# third try, a modal error box. Back off instead of retrying forever.
MAX_CONSECUTIVE_LAUNCH_FAILURES = 3
LAUNCH_FAILURE_COOLDOWN_SECONDS = 120

# Note: no CORS relaxation needed - umaserver sends Access-Control-Allow-Origin
# on every response, which is why Firefox (which has no CORS kill-switch for
# https pages) always worked.
FIREFOX_FORCED_PREFS = {
    # Firefox 150+ gates requests aimed at loopback/local addresses behind a
    # Local Network Access permission prompt ("<site> wants to access other apps
    # and services on this device", permission type loopback-network). The
    # helper page fetches our own server on 127.0.0.1, so it trips on every
    # fresh profile. 1 = ALLOW_ACTION, which makes the prompt auto-resolve.
    "permissions.default.loopback-network": 1,
}


def firefox_prefs_for(helper_url):
    """Forced prefs for a window pointed at `helper_url`.

    network.lna.skip-domains is checked twice against different hosts - once
    against the requesting site and once against the address being connected to
    - so both sides have to be listed for the Local Network Access check to be
    skipped outright.
    """
    prefs = dict(FIREFOX_FORCED_PREFS)
    helper_host = urlparse(helper_url).hostname
    domains = [d for d in (helper_host, "127.0.0.1", "localhost") if d]
    prefs["network.lna.skip-domains"] = ",".join(dict.fromkeys(domains))
    return prefs


def write_profile_user_js(profile_path, prefs):
    """Write `prefs` to user.js in a Firefox profile directory.

    user.js is the only file Firefox guarantees to read on every startup;
    prefs.js is owned by Firefox and rewritten when it exits. It also has to be
    rewritten on every launch rather than seeded once, because profiles created
    by older versions already exist on disk and would otherwise never pick up
    prefs added later.
    """
    lines = ["// Generated by Uma Launcher. Do not edit - rewritten on every launch.\n"]
    lines += [f"user_pref({json.dumps(key)}, {json.dumps(value)});\n"
              for key, value in prefs.items()]
    try:
        with open(os.path.join(profile_path, "user.js"), "w", encoding="utf-8") as f:
            f.writelines(lines)
    except OSError:
        # Not fatal: the prefs are also passed via Options below.
        logger.warning(f"Could not write user.js to {profile_path}:\n{traceback.format_exc()}")


def set_browser_version(options: ArgOptions, settings):
    if not settings['browser_version'] or not settings['browser_version'].strip():
        return
    options.browser_version = settings['browser_version']


def window_profile_dir(base_profile_path, url):
    """Per-window profile directory for `url`.

    A running browser instance holds an exclusive lock on its profile, and the
    helper and skills windows can run concurrently, so each window needs its own
    directory. Key on netloc+path only: the helper URL's query string encodes
    the deck and changes every career, and hashing it would spawn a fresh
    profile per run.
    """
    parsed_url = urlparse(url)
    url_slug = hashlib.md5(f"{parsed_url.netloc}{parsed_url.path}".encode("utf-8")).hexdigest()[:8]
    return f"{base_profile_path}_{url_slug}"

def firefox_setup(helper_url, settings):
    driver_path = None
    if settings['enable_browser_override']:
        new_path = settings['browser_custom_driver']
        if new_path:
            driver_path = new_path

    # Keep geckodriver's log out of the CWD (the install dir for the exe).
    firefox_service = FirefoxService(executable_path=driver_path,
                                     log_output=util.get_appdata("geckodriver.log"))
    firefox_service.creation_flags = CREATE_NO_WINDOW

    # Profile used IN PLACE via geckodriver's -profile argument. The
    # options.profile path clones the directory twice (copytree + base64-zip
    # extract), so Firefox only ever wrote to a throwaway copy and nothing -
    # cookies, site settings, "remember my choice" - survived a session. The
    # CLI argument is the one mechanism geckodriver documents as in-place.
    # Needs geckodriver >= 0.31.0 (Marionette port handling with custom
    # profiles); Selenium Manager fetches a current one automatically.
    base_profile = util.get_appdata("ff_profile")
    profile_dir = window_profile_dir(base_profile, helper_url)
    if not os.path.exists(profile_dir):
        # Seed from the legacy shared dir if present (keeps userChrome.css and
        # any manual tweaks), else from the bundled asset.
        seed = base_profile if os.path.exists(base_profile) else util.get_asset("ff_profile")
        shutil.copytree(seed, profile_dir)

    # Re-applied every launch so profiles created by older versions pick up
    # prefs added later; user_prefs the browser saves land in prefs.js and are
    # unaffected.
    forced_prefs = firefox_prefs_for(helper_url)
    write_profile_user_js(profile_dir, forced_prefs)

    options = webdriver.FirefoxOptions()
    set_browser_version(options, settings)
    options.add_argument("-profile")
    options.add_argument(profile_dir)
    # Also pass the forced prefs through Options: geckodriver applies these to
    # whatever profile it uses, so either path alone suffices and a change in
    # profile handling can't silently bring the prompt back.
    for pref_key, pref_value in forced_prefs.items():
        options.set_preference(pref_key, pref_value)

    binary_path = None

    if settings['enable_browser_override']:
        binary_path = settings['browser_custom_binary']
        if binary_path:
            options.binary_location = binary_path
    
    logger.debug(f"Firefox driver path: {driver_path}")
    logger.debug(f"Firefox binary path: {binary_path}")
    
    browser = webdriver.Firefox(service=firefox_service, options=options)
    _apply_firefox_adblock(browser, settings)
    browser.get(helper_url)
    return browser


UBLOCK_ADDON_ID = "uBlock0@raymondhill.net"


def _apply_firefox_adblock(browser, settings):
    """Install or remove the bundled uBlock Origin per the adblock setting.

    The profile is persistent and used in place, so an install survives
    restarts (installing again is a cheap upgrade/no-op) and disabling the
    setting has to actively uninstall. Never fatal: the helper works fine
    without it.
    """
    try:
        if settings['adblock_enabled']:
            xpi = util.get_asset("_assets/adblock/ublock_origin.xpi")
            if os.path.exists(xpi):
                browser.install_addon(xpi, temporary=False)
            else:
                logger.warning(f"Adblock enabled but bundled xpi missing: {xpi}")
        else:
            try:
                browser.uninstall_addon(UBLOCK_ADDON_ID)
            except WebDriverException:
                pass  # not installed - nothing to remove
    except Exception:
        logger.warning(f"Could not apply adblock setting:\n{traceback.format_exc()}")

def chromium_setup(service, options_class, driver_class, profile, helper_url, settings, binary_path=None):
    service.creation_flags = CREATE_NO_WINDOW
    options = options_class()
    set_browser_version(options, settings)

    if binary_path:
        options.binary_location = binary_path

    per_window_profile = window_profile_dir(profile, helper_url)

    options.add_argument(f"--user-data-dir={per_window_profile}")
    options.add_experimental_option("excludeSwitches", ["enable-automation"]) # Disable browser being controlled warning
    # No --disable-web-security: the only cross-origin traffic is helper page ->
    # umaserver, and umaserver sends CORS headers on every response. An
    # (elevated) browser session on a third-party site should not run with web
    # security disabled.
    # The launcher always runs elevated (util.elevate), and Chrome launched
    # elevated auto-de-elevates: it relaunches itself unelevated and the
    # original process exits, so chromedriver reports "Chrome instance exited"
    # while an orphaned, driverless window opens anyway. Every retry then
    # spawns another orphan. This switch tells Chrome to stay in the process
    # chromedriver spawned; it is a no-op when not elevated.
    options.add_argument("--do-not-de-elevate")

    if not settings['enable_browser_override']:
        options.add_argument("--app=" + helper_url)

    browser = driver_class(service=service, options=options)

    if settings['enable_browser_override']:
        browser.get(helper_url)

    logger.debug(f"Chromium started using profile {per_window_profile}")
    return browser

def chromium_service_kwargs(log_name, driver_path=None):
    """Service kwargs that capture why a Chromium browser failed to start.

    "Chrome instance exited" from the driver carries no reason; the driver's own
    verbose log has it (bad flag, profile lock, sandbox failure). Log to appdata
    the way geckodriver does, always verbose - it is a few KB per launch and it
    is the only record of a startup failure.
    """
    kwargs = {
        "log_output": util.get_appdata(log_name),
        "service_args": ["--verbose"],
    }
    if driver_path:
        kwargs["executable_path"] = driver_path
    return kwargs


def chrome_setup(helper_url, settings):
    driver_path = None
    if settings['enable_browser_override']:
        new_path = settings['browser_custom_driver']
        if new_path:
            driver_path = new_path

    binary_path = None
    if settings['enable_browser_override']:
        binary_path = settings['browser_custom_binary']

    logger.debug(f"Chrome driver path: {driver_path}")
    logger.debug(f"Chrome binary path: {binary_path}")

    return chromium_setup(
        service=ChromeService(**chromium_service_kwargs("chromedriver.log", driver_path)),
        options_class=webdriver.ChromeOptions,
        driver_class=webdriver.Chrome,
        profile=util.get_appdata("chr_profile"),
        helper_url=helper_url,
        settings=settings,
        binary_path=binary_path
    )

