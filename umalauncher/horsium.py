BROWSER_LIST = {
    'Firefox': firefox_setup,
    'Chrome': chrome_setup,
    'Edge': edge_setup,
}

def urls_match(url1, url2):
    """Whether two URLs point at the same page: netloc + path only.

    Query string and fragment are IGNORED on purpose. The helper URL's query
    encodes the deck (card/scenario/support ids) and changes every career, so
    exact matching would treat every new career as a different page and force
    a full reload instead of reusing the open tab.
    """
    url1 = url1[:-1] if url1.endswith('/') else url1
    url2 = url2[:-1] if url2.endswith('/') else url2
    urlparse1 = urlparse(url1)
    urlparse2 = urlparse(url2)
    return (urlparse1.netloc, urlparse1.path) == (urlparse2.netloc, urlparse2.path)


def ensure_focus(func):
    """Decorator for BrowserWindow methods that need a live, focused tab.

    Retries ensure_tab_open (which relaunches the browser if needed) up to 3
    times before running the wrapped method. If the browser still isn't up,
    reports the outage once - as a tray notification when the tray is
    available, falling back to the old modal warning box.
    """
    def wrapper(self, *args, **kwargs):
        with self._driver_lock:
            tries = 0

            while tries < 3:
                tries += 1
                self.ensure_tab_open()
                if self.driver:
                    return func(self, *args, **kwargs)

            # Report once per outage, not once per call - this runs off
            # packet handling, so it used to stack modal boxes forever.
            already_reported = self._reported_launch_failure
            self._reported_launch_failure = True

        if already_reported:
            return

        error_line = self.latest_error.strip() or "no error recorded"
        tray = getattr(self.threader, "tray", None)
        if tray and tray.notify(
                f"The helper browser could not be opened ({error_line}). "
                "Try selecting a different browser in the preferences.",
                "Uma Launcher: Unable to reach browser"):
            return
        # No tray (or toast failed): fall back to the modal box.
        util.show_warning_box("Uma Launcher: Unable to reach browser.", f"Webbrowser is unable to open.<br><br>If this problem persists, try restarting your computer<br>or selecting a different browser in the preferences.<br><br>Extra info:<br>{self.latest_error}")
    return wrapper


class BrowserWindow:
    def __init__(self, url, threader, rect=None, run_at_launch=None):
        self.url = url
        self.threader = threader
        self.settings = threader.settings
        self.driver: RemoteWebDriver = None
        self.active_tab_handle = None
        self.last_window_rect = {'x': rect[0], 'y': rect[1], 'width': rect[2], 'height': rect[3]} if rect else None
        self.run_at_launch = run_at_launch
        self.browser_name = "Auto"
        self.latest_error = ""
        # WebDriver sessions are not thread-safe, and this window is driven from
        # both the CarrotJuicer thread and the Flask (umaserver) thread. RLock
        # because locked methods call each other (ensure_focus -> ensure_tab_open).
        self._driver_lock = threading.RLock()
        self._consecutive_launch_failures = 0
        self._launch_blocked_until = 0.0
        self._reported_launch_failure = False

        self.ensure_tab_open()

    def init_browser(self) -> RemoteWebDriver:
        driver = None

        remaining_cooldown = self._launch_blocked_until - time.monotonic()
        if remaining_cooldown > 0:
            logger.debug(f"Browser launch backing off for another {remaining_cooldown:.0f}s")
            return None

        if self.settings['enable_browser_override']:
            selection = self.settings['custom_browser_type']
        else:
            selection = self.settings['selected_browser']
        browser_name = [
                    browser
                    for browser, selected in selection.items()
                    if selected
                ][0]
        self.browser_name = browser_name

        # Hack to convert override Chromium to Chrome
        if browser_name == 'Other (Chromium)':
            browser_name = 'Chrome'

        browser_list = []
        if browser_name == "Auto":
            browser_list = BROWSER_LIST.items()
        else:
            browser_list = [(browser_name, BROWSER_LIST[browser_name])]

        for browser_data in browser_list:
            browser_name, browser_setup = browser_data
            try:
                logger.info("Attempting " + str(browser_setup.__name__))
                driver = browser_setup(self.url, self.settings)
                self.browser_name = browser_name
                break
            except Exception as e:
                logger.error("Failed to start browser")
                logger.error(traceback.format_exc())
                self.latest_error = traceback.format_exception_only(type(e), e)[-1]
        if driver:
            self._consecutive_launch_failures = 0
            self._reported_launch_failure = False
        else:
            self._consecutive_launch_failures += 1
            if self._consecutive_launch_failures >= MAX_CONSECUTIVE_LAUNCH_FAILURES:
                self._launch_blocked_until = time.monotonic() + LAUNCH_FAILURE_COOLDOWN_SECONDS
                self._consecutive_launch_failures = 0
                logger.error(f"Browser failed to start {MAX_CONSECUTIVE_LAUNCH_FAILURES} times in a row; "
                             f"pausing launch attempts for {LAUNCH_FAILURE_COOLDOWN_SECONDS}s")

        if driver:
            # A hung page or script must raise instead of blocking the calling
            # thread forever (packet handling runs through this class).
            try:
                driver.set_page_load_timeout(30)
                driver.set_script_timeout(20)
            except WebDriverException:
                logger.warning(f"Could not set driver timeouts:\n{traceback.format_exc()}")
        return driver

    def alive(self):
        with self._driver_lock:
            if self.driver is None:
                return False
            try:
                return self.active_tab_handle in self.driver.window_handles
            except WebDriverException:
                return False

    def _reuse_existing_tab(self):
        """Try to keep using the current session. Returns True when the tab is
        usable and showing the right page; raises WebDriverException when the
        session is unusable and must be replaced."""
        if self.active_tab_handle not in self.driver.window_handles:
            raise WebDriverException("Active tab is gone")

        if self.driver.current_window_handle != self.active_tab_handle:
            if self.browser_name == 'Firefox':
                self.driver.switch_to.window(self.active_tab_handle)
            else:
                # App-mode Chrome/Edge can't reliably switch back; relaunch.
                raise WebDriverException("Active tab is no longer the current window")

        if urls_match(self.driver.current_url, self.url):
            if self.driver.execute_script("return window.from_script;"):
                self.last_window_rect = self.driver.get_window_rect()
                return True

        # Wrong page: navigate. get() blocks until the load finishes or the
        # page-load timeout raises - no marker-polling needed.
        self.driver.get(self.url)
        self.run_script_at_launch()
        return True

    def ensure_tab_open(self):
        with self._driver_lock:
            if self.driver:
                try:
                    if self._reuse_existing_tab():
                        return
                except WebDriverException:
                    logger.warning(f"Browser session unusable, replacing it:\n{traceback.format_exc()}")
                    # Quit off-thread: a dead session's quit() can block on the
                    # wire, and this path runs inside packet handling.
                    _quit_driver_async(self.driver)
                    self.driver = None

            self.driver = self.init_browser()

            try:
                if not self.driver or not self.driver.window_handles:
                    return
            except WebDriverException:
                logger.error("Failed to get window handles")
                logger.error(traceback.format_exc())
                return

            self.active_tab_handle = self.driver.window_handles[0]
            self.driver.switch_to.window(self.active_tab_handle)
            self.run_script_at_launch()
            self.last_window_rect = self.driver.get_window_rect()

    def run_script_at_launch(self):
        self.driver.execute_script("""window.from_script = true;""")
        if self.last_window_rect:
            self.driver.set_window_rect(self.last_window_rect['x'], self.last_window_rect['y'], self.last_window_rect['width'], self.last_window_rect['height'])
        if self.run_at_launch is not None:
            self.run_at_launch(self)

        # only want to do this for the training-event-helper
        if 'training-event-helper' in self.url:
            self.set_topmost(self.settings["browser_topmost"])

    def get_browser_pid(self):
        if self.driver is None:
            return None
        # Firefox reports its PID directly.
        if 'moz:processID' in self.driver.capabilities:
            return self.driver.capabilities['moz:processID']
        # Chromium: the browser is the driver service's direct child - no need
        # to scan the system process table.
        try:
            service_process = self.driver.service.process
            if service_process:
                children = psutil.Process(service_process.pid).children()
                if children:
                    return children[0].pid
        except (psutil.Error, AttributeError):
            logger.warning(f"Error getting browser PID from driver service:\n{traceback.format_exc()}")
        logger.warning("Could not get browser PID!")
        return None

    # TODO: It'd be nice to be able to do this without resorting to the win32 API
    def set_topmost(self, is_topmost):
        hwnd = util.get_window_handle_from_pid( self.get_browser_pid() )
        if hwnd is None:
            logger.error("Could not find window handle for browser PID.")
            return
        rect = util.get_window_rect(hwnd)
        # GetWindowRect returns (left, top, right, bottom), but we want (x, y, width, height)
        # TODO does this need flags?
        if is_topmost:
            logger.info( "Enabling always on top")
            win32gui.SetWindowPos(hwnd, win32con.HWND_TOPMOST, rect[0], rect[1], rect[2] - rect[0], rect[3] - rect[1], 0)
        else:
            logger.info( "Disabling always on top")
            win32gui.SetWindowPos(hwnd, win32con.HWND_NOTOPMOST, rect[0], rect[1], rect[2] - rect[0], rect[3] - rect[1], 0)
        self.settings["browser_topmost"] = is_topmost

    @ensure_focus
    def execute_script(self, *args, **kwargs):
        return self.driver.execute_script(*args, **kwargs)

    @ensure_focus
    def set_window_rect(self, rect):
        return self.driver.set_window_rect(*rect)
    
    @ensure_focus
    def get_window_rect(self):
        return self.driver.get_window_rect()

    def get_last_window_rect(self):
        return self.last_window_rect
    
    def current_url(self):
        return self.url

    def close(self):
        # Only close the active tab
        with self._driver_lock:
            try:
                if self.driver is not None and self.active_tab_handle in self.driver.window_handles:
                    self.driver.switch_to.window(self.active_tab_handle)
                    self.last_window_rect = self.driver.get_window_rect()
                    self.driver.close()
            except (NoSuchWindowException, WebDriverException):
                pass

    def quit(self):
        with self._driver_lock:
            self.close()
            _quit_driver_async(self.driver)
            self.driver = None


def quit_one_driver(driver):
    logger.debug(f"Closing driver in thread {threading.get_ident()}")
    if driver:
        try:
            driver.quit()
        except (NoSuchWindowException, WebDriverException):
            pass
    logger.debug(f"Finished closing driver in thread {threading.get_ident()}")

def _quit_driver_async(driver):
    """Quit a driver on a background thread, immediately.

    Replaced/hung sessions used to accumulate in a global list that was only
    drained at shutdown, leaving dead browser + driver processes running for
    the whole app session. Quitting can block on the wire, so it happens
    off-thread; threads are tracked so shutdown can join them.
    """
    if not driver:
        return
    quit_thread = threading.Thread(target=quit_one_driver, args=(driver,), daemon=True)
    _PENDING_QUIT_THREADS.append(quit_thread)
    quit_thread.start()

def quit_all_drivers():
    """Wait for any in-flight driver quits (bounded) at shutdown."""
    for quit_thread in _PENDING_QUIT_THREADS:
        quit_thread.join(timeout=10)
    _PENDING_QUIT_THREADS.clear()

